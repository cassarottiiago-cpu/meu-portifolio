// Run only after visual inspection of the composed viewport capture.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname,'..');
const candidate = path.join(root,'validacao/limo-26/limozine-completo-viewport.webp');
const metadata = JSON.parse(fs.readFileSync(candidate.replace('.webp','.json'),'utf8'));
assert.equal(metadata.url,'https://lplimozine-nu.vercel.app/');
assert.equal(metadata.tiles[0].documentY,0);
for(let i=1;i<metadata.tiles.length;i++) assert.equal(metadata.tiles[i].documentY,metadata.tiles[i-1].documentY+metadata.tiles[i-1].height);
const destination=path.join(root,'assets/revisao-23/limozine-completo.webp');
const backup=path.join(root,'validacao/limo-26/limozine-completo-anterior.webp');
if(!fs.existsSync(backup)) fs.copyFileSync(destination,backup);
fs.copyFileSync(candidate,destination);
const file=path.join(root,'assets/revisao-23/limozine-metadata.json');
const record=JSON.parse(fs.readFileSync(file,'utf8'));
Object.assign(record.files.find(item=>item.role==='completo'),{width:metadata.width,height:metadata.height,bytes:metadata.bytes,capturedAt:metadata.capturedAt,method:metadata.method});
record.fullCapture=metadata;
fs.writeFileSync(file,JSON.stringify(record,null,2)+'\n');
console.log('Captura longa promovida; versão anterior preservada em validacao/limo-26.');
